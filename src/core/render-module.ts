import { indentTail, jsdoc, text } from "./jsdoc"
import { acceptsJson, defaultMediaType, isApplicationJson } from "./media-types"
import type { Declaration, Field, Info, Media, Model, Operation } from "./model"
import { propertyKey } from "./naming"
import type { TypeContext } from "./render-types"
import { block, indexOf, renderFields, renderType } from "./render-types"

/**
 * Render the model as a TypeScript module that imports nothing: its types, and the runtime
 * `contract` for openapi-shape/client.
 */
export function renderModule(model: Model): string {
  // Inside `Schemas`, a schema named `Blob` would capture raw bytes.
  const shadowed = model.declarations.some((d) => d.name === "Blob" || d.inputName === "Blob")
  const inside = (side: TypeContext["side"]): TypeContext => ({
    side,
    refPrefix: "",
    blob: shadowed ? "globalThis.Blob" : "Blob",
  })

  const parts = [header(model.info)]
  parts.push(operations("Endpoints", model.endpoints, outside, false))
  // The API sends webhook and callback requests, and receives their responses.
  if (model.webhooks.length > 0) {
    parts.push(operations("Webhooks", model.webhooks, outside, true))
  }
  if (model.callbacks.length > 0) {
    parts.push(operations("Callbacks", model.callbacks, outside, true))
  }
  if (model.declarations.length > 0) parts.push(schemas(model.declarations, inside))
  parts.push(contract(model.endpoints))
  return `${parts.join("\n\n")}\n`
}

function outside(side: TypeContext["side"]): TypeContext {
  return { side, refPrefix: "Schemas.", blob: "Blob" }
}

function header(info: Info): string {
  const lines: string[] = []
  const title = [info.title, info.version].filter((v) => v !== undefined).join(" ")
  if (title !== "") lines.push(text(title).replaceAll("\n", " "))
  if (info.description !== undefined) lines.push(...text(info.description).split("\n"))
  if (lines.length > 0) lines.push("")
  if (info.servers.length > 0) {
    lines.push(...info.servers.map((url) => `Server: ${text(url).replaceAll("\n", " ")}`), "")
  }
  lines.push(`Generated by openapi-shape from an OpenAPI ${info.openapi} document. Do not edit.`)
  return lines.map((line) => (line === "" ? "//" : `// ${line}`)).join("\n")
}

function operations(
  name: string,
  list: Operation[],
  context: (side: TypeContext["side"]) => TypeContext,
  incoming: boolean,
): string {
  const entries = list.map((operation) => {
    const request = context(incoming ? "response" : "request")
    const response = context(incoming ? "request" : "response")
    const members: string[] = []
    if (operation.params.length > 0)
      members.push(`params: ${renderFields(operation.params, undefined, request)}`)
    if (operation.querystring) {
      const optional = operation.querystring.required ? "" : "?"
      members.push(
        `${jsdoc(operation.querystring.annotations)}query${optional}: ${renderType(operation.querystring.type, request)}`,
      )
    } else if (operation.query.length > 0) {
      members.push(`query: ${renderFields(operation.query, undefined, request)}`)
    }
    if (operation.headers.length > 0)
      members.push(`headers: ${renderFields(operation.headers, undefined, request)}`)
    if (operation.cookies.length > 0)
      members.push(`cookies: ${renderFields(operation.cookies, undefined, request)}`)
    if (operation.body) {
      const optional = operation.body.required ? "" : "?"
      members.push(
        `${jsdoc(operation.body.annotations)}body${optional}: ${contentMap(operation.body.content, request)}`,
      )
    }
    const responses = operation.responses.map((r) => {
      const parts: string[] = []
      if (r.headers.length > 0)
        parts.push(`headers: ${renderFields(r.headers, undefined, response)}`)
      if (r.content.length > 0) parts.push(`content: ${contentMap(r.content, response)}`)
      return `${jsdoc(r.annotations)}${JSON.stringify(r.status)}: ${block(parts)}`
    })
    members.push(`responses: ${block(responses)}`)
    const body = members.map((member) => indentTail(member, "  ")).join("\n  ")
    return `${jsdoc(operation.annotations)}${JSON.stringify(operation.key)}: {\n  ${body}\n}`
  })
  const lines = entries.map((entry) => `  ${indentTail(entry, "  ")}`)
  return lines.length === 0
    ? `export interface ${name} {}`
    : `export interface ${name} {\n${lines.join("\n")}\n}`
}

/** Media type → content type. */
function contentMap(content: Media[], context: TypeContext): string {
  return block(
    content.map(
      (media) => `${JSON.stringify(media.mediaType)}: ${renderType(media.type, context)}`,
    ),
  )
}

function schemas(
  declarations: Declaration[],
  context: (side: TypeContext["side"]) => TypeContext,
): string {
  const rendered: string[] = []
  for (const declaration of declarations) {
    rendered.push(declare(declaration.name, declaration, context("response")))
    if (declaration.inputName !== undefined) {
      rendered.push(declare(declaration.inputName, declaration, context("request")))
    }
  }
  const body = rendered.map((d) => `  ${indentTail(d, "  ")}`).join("\n\n")
  return `export namespace Schemas {\n${body}\n}`
}

function declare(name: string, declaration: Declaration, context: TypeContext): string {
  const annotations = jsdoc(declaration.annotations)
  const type = declaration.type
  if (type.kind === "object") {
    return `${annotations}export interface ${name} ${renderFields(type.fields, indexOf(type), context, true)}`
  }
  return `${annotations}export type ${name} = ${renderType(type, context)}`
}

/** The format version written here must agree with openapi-shape/client's `Contract`. */
const CONTRACT_VERSION = 2

/**
 * How requests go over the wire, for `openapi-shape/client`: each endpoint's serialization and
 * default media type, where they differ from OpenAPI's defaults.
 */
function contract(endpoints: Operation[]): string {
  const entries = Object.fromEntries(
    endpoints.flatMap((operation) => {
      const entry = contractEntry(operation)
      return entry ? [[operation.key, entry]] : []
    }),
  )
  // Typed here, not by openapi-shape/client, so that the module imports nothing:
  // createClient checks it, `version` above all, and infers `Endpoints` from `types`.
  return [
    "/** Request serialization settings, including schema-derived form defaults. */",
    `const endpoints = ${literal(entries, "", 0, true)} as const`,
    "",
    "/** How requests go over the wire, for `createClient(contract)` from openapi-shape/client. */",
    "export const contract: {",
    "  /** The contract's format; `createClient` refuses one it does not read. */",
    `  readonly version: ${CONTRACT_VERSION}`,
    "  /** Carries `Endpoints` for `createClient` to infer; never set. */",
    "  readonly types?: Endpoints",
    "  readonly endpoints: typeof endpoints",
    `} = { version: ${CONTRACT_VERSION}, endpoints }`,
  ].join("\n")
}

function contractEntry(operation: Operation): Record<string, unknown> | undefined {
  // The client sends no body with GET or HEAD, as fetch cannot.
  const method = operation.key.slice(0, operation.key.indexOf(" ")).toUpperCase()
  const content = method === "GET" || method === "HEAD" ? [] : (operation.body?.content ?? [])
  const fallback = defaultMediaType(content.map((media) => media.mediaType))
  const entry: Record<string, unknown> = {
    params: fieldEncodings(operation.params),
    query: fieldEncodings(operation.query) ?? operation.querystring?.encoding,
    querystring: operation.querystring?.mediaType,
    headers: fieldEncodings(operation.headers),
    // Sent when the call names no media type, for any body, where it is not JSON.
    contentType: fallback !== undefined && !acceptsJson(fallback) ? fallback : undefined,
    // The label of the JSON the client encodes then, where it is not plain application/json.
    json:
      fallback !== undefined && isApplicationJson(fallback) && fallback !== "application/json"
        ? fallback
        : undefined,
    // Keep each form variant's encodings attached to its full media type.
    bodyEncodings: content.some((media) => media.encoding)
      ? Object.fromEntries(
          content.flatMap((media) => (media.encoding ? [[media.mediaType, media.encoding]] : [])),
        )
      : undefined,
  }
  for (const key of Object.keys(entry)) if (entry[key] === undefined) delete entry[key]
  return Object.keys(entry).length > 0 ? entry : undefined
}

function fieldEncodings(fields: Field[]): Record<string, unknown> | undefined {
  const entries = fields.flatMap((f) => (f.encoding ? [[f.name, f.encoding]] : []))
  return entries.length > 0 ? Object.fromEntries(entries) : undefined
}

const WIDTH = 100

/**
 * A JavaScript value literal with identifier keys unquoted: on one line when it fits within `WIDTH`
 * from `column`, else one entry per line.
 */
function literal(value: unknown, indent = "", column = indent.length, expand = false): string {
  const flat = flatLiteral(value)
  if (typeof value !== "object" || value === null) return flat
  // The trailing comma needs a column too.
  if (!expand && column + flat.length < WIDTH) return flat
  const inner = `${indent}  `
  const lines = Array.isArray(value)
    ? value.map((item) => `${inner}${literal(item, inner)},`)
    : Object.entries(value).map(([key, item]) => {
        const head = `${literalKey(key)}: `
        return `${inner}${head}${literal(item, inner, inner.length + head.length)},`
      })
  if (lines.length === 0) return flat
  const [open, close] = Array.isArray(value) ? ["[", "]"] : ["{", "}"]
  return `${open}\n${lines.join("\n")}\n${indent}${close}`
}

function flatLiteral(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map((item) => flatLiteral(item)).join(", ")}]`
  if (typeof value === "object" && value !== null) {
    const entries = Object.entries(value).map(([k, v]) => `${literalKey(k)}: ${flatLiteral(v)}`)
    return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`
  }
  return JSON.stringify(value)
}

/** An object literal key; `__proto__` is computed, or it would set the prototype. */
function literalKey(key: string): string {
  return key === "__proto__" ? '["__proto__"]' : propertyKey(key)
}
