import { CONTRACT_VERSION } from "../shared/contract"
import { indentTail, jsdoc, text } from "./jsdoc"
import type { Info, Media, OperationModel, TypeDeclaration } from "./model"
import { propertyKey } from "./naming"
import type { EndpointOutput, ModuleModel } from "./prepare-output"
import type { TypeContext } from "./render-types"
import { block, indexOf, renderFields, renderType } from "./render-types"

/**
 * Render the model as a TypeScript module that imports nothing: its types, and the runtime
 * `contract` for openapi-shape/client.
 */
export async function renderModule(
  model: ModuleModel,
  workpoint?: () => Promise<void> | undefined,
): Promise<string> {
  // Inside `Schemas`, a schema named `Blob` would capture raw bytes.
  const shadowed = model.declarations.some((d) => d.name === "Blob" || d.inputName === "Blob")
  const inside: TypeContext = {
    refPrefix: "",
    blob: shadowed ? "globalThis.Blob" : "Blob",
  }

  const parts = [header(model.info)]
  parts.push(await operations("Endpoints", model.operations, outside, workpoint))
  // The API sends webhook and callback requests, and receives their responses.
  if (model.webhooks.length > 0) {
    parts.push(await operations("Webhooks", model.webhooks, outside, workpoint))
  }
  if (model.callbacks.length > 0) {
    parts.push(await operations("Callbacks", model.callbacks, outside, workpoint))
  }
  if (model.declarations.length > 0)
    parts.push(await schemas(model.declarations, inside, workpoint))
  parts.push(await contract(model.operations, workpoint))
  return `${parts.join("\n\n")}\n`
}

const outside: TypeContext = { refPrefix: "Schemas.", blob: "Blob" }

function header(info: Info): string {
  const lines: string[] = []
  const title = [info.title, info.version].filter((v) => v !== undefined).join(" ")
  if (title !== "") lines.push(text(title).replaceAll("\n", " "))
  if (info.description !== undefined) lines.push(...text(info.description).split("\n"))
  lines.push(`@version ${info.openapi}`)
  for (const url of info.servers) lines.push(`@server ${text(url).replaceAll("\n", " ")}`)
  return [
    "/* eslint-disable */",
    "// @ts-nocheck",
    "// biome-ignore-all lint: Generated file.",
    "// oxlint-disable",
    "// ---------------------------------------",
    ...lines.map((line) => {
      // Metadata must remain prose even when it resembles a compiler or linter directive.
      const directive = /^\s*(?:@ts-|eslint-|biome-|oxlint-|prettier-|oxfmt-)/i.test(line)
      return line === "" ? "//" : `// ${directive ? "| " : ""}${line}`
    }),
    "// ---------------------------------------",
    "// Generated by openapi-shape. Do not edit.",
  ].join("\n")
}

async function operations(
  name: string,
  list: OperationModel[],
  context: TypeContext,
  workpoint?: () => Promise<void> | undefined,
): Promise<string> {
  const entries: string[] = []
  for (const operation of list) {
    const members: string[] = []
    if (operation.params.length > 0)
      members.push(`params: ${renderFields(operation.params, undefined, context)}`)
    if (operation.querystring) {
      const optional = operation.querystring.required ? "" : "?"
      members.push(
        `${jsdoc(operation.querystring.annotations)}query${optional}: ${renderType(operation.querystring.type, context)}`,
      )
    } else if (operation.query.length > 0) {
      const optional = operation.query.some((field) => field.required) ? "" : "?"
      members.push(`query${optional}: ${renderFields(operation.query, undefined, context)}`)
    }
    if (operation.headers.length > 0)
      members.push(`headers: ${renderFields(operation.headers, undefined, context)}`)
    if (operation.cookies.length > 0)
      members.push(`cookies: ${renderFields(operation.cookies, undefined, context)}`)
    if (operation.body) {
      const optional = operation.body.required ? "" : "?"
      members.push(
        `${jsdoc(operation.body.annotations)}body${optional}: ${contentMap(operation.body.content, context)}`,
      )
    }
    const responses = operation.responses.map((r) => {
      const parts: string[] = []
      if (r.headers.length > 0)
        parts.push(`headers: ${renderFields(r.headers, undefined, context)}`)
      if (r.content.length > 0) parts.push(`content: ${contentMap(r.content, context)}`)
      return `${jsdoc(r.annotations)}${JSON.stringify(r.status)}: ${block(parts)}`
    })
    members.push(`responses: ${block(responses)}`)
    const body = members.map((member) => indentTail(member, "  ")).join("\n  ")
    entries.push(`${jsdoc(operation.annotations)}${JSON.stringify(operation.key)}: {\n  ${body}\n}`)
    const pending = workpoint?.()
    // oxlint-disable-next-line no-await-in-loop -- yield between independent operations
    if (pending) await pending
  }
  const lines = entries.map((entry) => `  ${indentTail(entry, "  ")}`)
  return lines.length === 0
    ? `export interface ${name} {}`
    : `export interface ${name} {\n${lines.join("\n")}\n}`
}

/** Media type → content type. */
function contentMap(content: Media[], context: TypeContext): string {
  return block(
    content.map(
      (media) => `${JSON.stringify(media.mediaType)}: ${renderType(media.type, context)}`,
    ),
  )
}

async function schemas(
  declarations: TypeDeclaration[],
  context: TypeContext,
  workpoint?: () => Promise<void> | undefined,
): Promise<string> {
  const rendered: string[] = []
  for (const declaration of declarations) {
    rendered.push(declare(declaration.name, declaration, context))
    const pending = workpoint?.()
    // oxlint-disable-next-line no-await-in-loop -- yield between independent declarations
    if (pending) await pending
  }
  const body = rendered.map((d) => `  ${indentTail(d, "  ")}`).join("\n\n")
  return `export namespace Schemas {\n${body}\n}`
}

function declare(name: string, declaration: TypeDeclaration, context: TypeContext): string {
  const annotations = jsdoc(declaration.annotations)
  const type = declaration.type
  if (type.kind === "object") {
    return `${annotations}export interface ${name} ${renderFields(type.fields, indexOf(type), context, true)}`
  }
  return `${annotations}export type ${name} = ${renderType(type, context)}`
}

/**
 * How requests go over the wire, for `openapi-shape/client`: each endpoint's serialization, request
 * media, and response declarations.
 */
async function contract(
  entriesToRender: EndpointOutput[],
  workpoint?: () => Promise<void> | undefined,
): Promise<string> {
  const entries: string[] = []
  for (const operation of entriesToRender) {
    const entry = operation.contract
    entries.push(`  ${literalKey(operation.key)}: ${flatLiteral(entry)},`)
    const pending = workpoint?.()
    // oxlint-disable-next-line no-await-in-loop -- yield between independent endpoint encodings
    if (pending) await pending
  }
  const value = entries.length === 0 ? "{}" : `{\n${entries.join("\n")}\n}`
  // Typed here, not by openapi-shape/client, so that the module imports nothing:
  // createClient checks it, `version` above all, and infers `Endpoints` from `types`.
  return [
    "// prettier-ignore",
    "const endpoints =",
    "  // biome-ignore format: Preserve generated endpoint layout.",
    `  ${value.replaceAll("\n", "\n  ")} as const`,
    "",
    "export const contract: {",
    `  readonly version: ${CONTRACT_VERSION}`,
    "  readonly types?: Endpoints",
    "  readonly endpoints: typeof endpoints",
    `} = { version: ${CONTRACT_VERSION}, endpoints }`,
  ].join("\n")
}

function flatLiteral(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map((item) => flatLiteral(item)).join(", ")}]`
  if (typeof value === "object" && value !== null) {
    const entries = Object.entries(value).map(([k, v]) => `${literalKey(k)}: ${flatLiteral(v)}`)
    return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`
  }
  return JSON.stringify(value)
}

/** An object literal key; `__proto__` is computed, or it would set the prototype. */
function literalKey(key: string): string {
  return key === "__proto__" ? '["__proto__"]' : propertyKey(key)
}
