import type { Contract, Declaration, Field, Info, Operation, Response } from "../contract/model"
import { acceptsJson } from "../shared/media"
import { propertyKey, toIdentifier, uniqueName } from "../shared/naming"
import { indentTail, jsdoc, text } from "./jsdoc"
import type { TypeContext } from "./type"
import { block, indexOf, renderFields, renderType } from "./type"

export interface RenderOptions {
  /** OpenAPI `format` → TypeScript type expressions, applied to strings, numbers, and binary data. */
  formats?: Record<string, string>
  /** Types only (for a `.d.ts` file): leave out `Security` and the runtime `contract`. */
  declarations?: boolean
}

/** Render the contract as a TypeScript module. */
export function renderDeclarations(contract: Contract, options: RenderOptions = {}): string {
  const formats = { binary: "Blob", ...options.formats }
  // Inside `Schemas`, a schema named like a type a format maps to (`Date`,
  // `Blob`) would capture it; such mappings go through a module-level alias.
  const names = new Set(contract.declarations.flatMap((d) => [d.name, d.inputName ?? d.name]))
  const taken = new Set(names)
  for (const name of ["Endpoints", "Webhooks", "Callbacks", "Schemas", "Security", "Contract"]) {
    taken.add(name)
  }
  const aliases: string[] = []
  const insideFormats: Record<string, string> = { ...formats }
  const namingSchemas = new Set<string>()
  for (const [format, type] of Object.entries(formats)) {
    const identifiers = type.match(/[\p{L}_$][\p{L}\p{N}_$]*/gu) ?? []
    if (!identifiers.some((id) => names.has(id))) continue
    namingSchemas.add(format)
    const alias = uniqueName(`Format_${toIdentifier(format)}`, taken)
    taken.add(alias)
    aliases.push(`type ${alias} = ${type}`)
    insideFormats[format] = alias
  }
  const outside = (view: TypeContext["view"]): TypeContext => ({
    view,
    refPrefix: "Schemas.",
    formats,
    namingSchemas,
  })
  const inside = (view: TypeContext["view"]): TypeContext => ({
    view,
    refPrefix: "",
    formats: insideFormats,
    namingSchemas,
  })

  const withClient = !options.declarations
  const parts = [header(contract.info)]
  if (withClient) parts.push('import type { Contract } from "openapi-shape/client"')
  parts.push(operations("Endpoints", contract.endpoints, outside, false))
  // The API sends webhook and callback requests, and receives their responses.
  if (contract.webhooks.length > 0) {
    parts.push(operations("Webhooks", contract.webhooks, outside, true))
  }
  if (contract.callbacks.length > 0) {
    parts.push(operations("Callbacks", contract.callbacks, outside, true))
  }
  if (contract.declarations.length > 0) parts.push(schemas(contract.declarations, inside))
  if (aliases.length > 0) parts.push(aliases.join("\n"))
  if (withClient) parts.push(...client(contract))
  return `${parts.join("\n\n")}\n`
}

function header(info: Info): string {
  const lines: string[] = []
  const title = [info.title, info.version].filter((v) => v !== undefined).join(" ")
  if (title !== "") lines.push(text(title).replaceAll("\n", " "))
  if (info.description !== undefined) lines.push(...text(info.description).split("\n"))
  if (lines.length > 0) lines.push("")
  lines.push(`Generated by openapi-shape from an OpenAPI ${info.openapi} document. Do not edit.`)
  return lines.map((line) => (line === "" ? "//" : `// ${line}`)).join("\n")
}

function operations(
  name: string,
  list: Operation[],
  context: (view: TypeContext["view"]) => TypeContext,
  incoming: boolean,
): string {
  const entries = list.map((operation) => {
    const request = context(incoming ? "response" : "request")
    const response = context(incoming ? "request" : "response")
    const members: string[] = []
    if (operation.params.length > 0)
      members.push(`params: ${renderFields(operation.params, undefined, request)}`)
    if (operation.querystring) {
      const optional = operation.querystring.required ? "" : "?"
      members.push(
        `${jsdoc(operation.querystring.docs)}query${optional}: ${renderType(operation.querystring.type, request)}`,
      )
    } else if (operation.query.length > 0) {
      members.push(`query: ${renderFields(operation.query, undefined, request)}`)
    }
    if (operation.headers.length > 0)
      members.push(`headers: ${renderFields(operation.headers, undefined, request)}`)
    if (operation.cookies.length > 0)
      members.push(`cookies: ${renderFields(operation.cookies, undefined, request)}`)
    if (operation.body) {
      const content = operation.body.content.map(
        (media) => `${JSON.stringify(media.mediaType)}: ${renderType(media.type, request)}`,
      )
      members.push(
        `${jsdoc(operation.body.docs)}body${operation.body.required ? "" : "?"}: ${block(content)}`,
      )
    }
    members.push(
      `response: ${responseMap(operation.responses, (r) => renderType(r.type, response), true)}`,
    )
    if (operation.responses.some((r) => r.headers.length > 0)) {
      const withHeaders = operation.responses.filter((r) => r.headers.length > 0)
      members.push(
        `responseHeaders: ${responseMap(withHeaders, (r) => renderFields(r.headers, undefined, response), false)}`,
      )
    }
    const body = members.map((member) => indentTail(member, "  ")).join("\n  ")
    return `${jsdoc(operation.docs)}${JSON.stringify(operation.key)}: {\n  ${body}\n}`
  })
  const lines = entries.map((entry) => `  ${indentTail(entry, "  ")}`)
  return lines.length === 0
    ? `export interface ${name} {}`
    : `export interface ${name} {\n${lines.join("\n")}\n}`
}

function responseMap(
  responses: Response[],
  value: (r: Response) => string,
  withDocs: boolean,
): string {
  return block(
    responses.map(
      (r) => `${withDocs ? jsdoc(r.docs) : ""}${JSON.stringify(r.status)}: ${value(r)}`,
    ),
  )
}

function schemas(
  declarations: Declaration[],
  context: (view: TypeContext["view"]) => TypeContext,
): string {
  const rendered: string[] = []
  for (const declaration of declarations) {
    rendered.push(declare(declaration.name, declaration, context("response")))
    if (declaration.inputName !== undefined) {
      rendered.push(declare(declaration.inputName, declaration, context("request")))
    }
  }
  const body = rendered.map((d) => `  ${indentTail(d, "  ")}`).join("\n\n")
  return `export namespace Schemas {\n${body}\n}`
}

function declare(name: string, declaration: Declaration, context: TypeContext): string {
  const docs = jsdoc(declaration.docs)
  const type = declaration.type
  if (type.kind === "object") {
    return `${docs}export interface ${name} ${renderFields(type.fields, indexOf(type), context, true)}`
  }
  return `${docs}export type ${name} = ${renderType(type, context)}`
}

/**
 * What `openapi-shape/client` needs beyond `Endpoints`: the credentials each
 * security scheme takes (`Security`), and how requests go over the wire
 * (`contract`), where that differs from OpenAPI's defaults.
 */
function client(contract: Contract): string[] {
  const { servers, security, requires } = contract.runtime
  const credentials = Object.entries(security).flatMap(([name, scheme]) => {
    // Mutual TLS is configured on the transport, not passed per request.
    if (scheme.type === "mutualTLS") return []
    const basic = scheme.type === "http" && scheme.scheme === "basic"
    return [`${propertyKey(name)}?: ${basic ? "{ username: string; password: string }" : "string"}`]
  })
  const data: Record<string, unknown> = { servers }
  if (Object.keys(security).length > 0) data.security = security
  if (requires) data.requires = requires
  data.endpoints = Object.fromEntries(
    contract.endpoints.flatMap((operation) => {
      const entry = contractEntry(operation)
      return entry ? [[operation.key, entry]] : []
    }),
  )
  const out: string[] = []
  if (credentials.length > 0) {
    out.push(
      `/** Credentials for \`createClient({ security })\`, by security scheme. */\nexport interface Security ${block(credentials, true)}`,
    )
  }
  const type = credentials.length > 0 ? "Contract<Endpoints, Security>" : "Contract<Endpoints>"
  out.push(
    `/** How requests go over the wire, for \`createClient({ contract })\` from openapi-shape/client. */\nexport const contract: ${type} = ${literal(data, "", 0, true)}`,
  )
  return out
}

/** An endpoint's serialization, media type, security, and servers where they differ from the defaults. */
function contractEntry(operation: Operation): Record<string, unknown> | undefined {
  const content = operation.body?.content ?? []
  const encoding = Object.fromEntries(
    content.flatMap((media) => (media.encoding ? [[media.mediaType, media.encoding]] : [])),
  )
  const entry: Record<string, unknown> = {
    servers: operation.servers,
    requires: operation.requires,
    params: fieldEncodings(operation.params),
    query: fieldEncodings(operation.query) ?? operation.querystring?.encoding,
    querystring: operation.querystring?.mediaType,
    headers: fieldEncodings(operation.headers),
    cookies: fieldEncodings(operation.cookies),
    // Sent when the call names no media type: JSON where accepted, else the only one declared.
    contentType:
      content.length === 1 && !acceptsJson(content[0].mediaType) ? content[0].mediaType : undefined,
    encoding: Object.keys(encoding).length > 0 ? encoding : undefined,
  }
  for (const key of Object.keys(entry)) if (entry[key] === undefined) delete entry[key]
  return Object.keys(entry).length > 0 ? entry : undefined
}

function fieldEncodings(fields: Field[]): Record<string, unknown> | undefined {
  const entries = fields.flatMap((f) => (f.encoding ? [[f.name, f.encoding]] : []))
  return entries.length > 0 ? Object.fromEntries(entries) : undefined
}

const WIDTH = 100

/**
 * A JavaScript value literal with identifier keys unquoted: on one line when it
 * fits within `WIDTH` from `column`, else one entry per line.
 */
function literal(value: unknown, indent = "", column = indent.length, expand = false): string {
  const flat = flatLiteral(value)
  if (typeof value !== "object" || value === null) return flat
  // The trailing comma needs a column too.
  if (!expand && column + flat.length < WIDTH) return flat
  const inner = `${indent}  `
  const lines = Array.isArray(value)
    ? value.map((item) => `${inner}${literal(item, inner)},`)
    : Object.entries(value).map(([key, item]) => {
        const head = `${literalKey(key)}: `
        return `${inner}${head}${literal(item, inner, inner.length + head.length)},`
      })
  if (lines.length === 0) return flat
  const [open, close] = Array.isArray(value) ? ["[", "]"] : ["{", "}"]
  return `${open}\n${lines.join("\n")}\n${indent}${close}`
}

function flatLiteral(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map((item) => flatLiteral(item)).join(", ")}]`
  if (typeof value === "object" && value !== null) {
    const entries = Object.entries(value).map(([k, v]) => `${literalKey(k)}: ${flatLiteral(v)}`)
    return entries.length === 0 ? "{}" : `{ ${entries.join(", ")} }`
  }
  return JSON.stringify(value)
}

/** An object literal key; `__proto__` is computed, or it would set the prototype. */
function literalKey(key: string): string {
  return key === "__proto__" ? '["__proto__"]' : propertyKey(key)
}
