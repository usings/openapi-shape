import { execFile } from "node:child_process"
import { existsSync, readFileSync, readdirSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { promisify } from "node:util"
import { describe, expect, it } from "vitest"
import { generate } from "../src/core/index"
import { withFiles } from "./helpers/tmp"
import { typecheck } from "./helpers/tsc"

// Documentation and tests share the published example description.
const ROOT = join(import.meta.dirname, "..")
const PAGES = [
  "README.md",
  ...readdirSync(join(ROOT, "docs"))
    .filter((name) => name.endsWith(".md"))
    .map((name) => `docs/${name}`),
]
const TEXT = Object.fromEntries(PAGES.map((page) => [page, readFileSync(join(ROOT, page), "utf8")]))
const LINKS = Object.entries(TEXT).flatMap(([page, markdown]) =>
  [...markdown.matchAll(/\]\((\.{1,2}\/[^)\s]*|#[^)\s]*)\)/g)].map(([, target]) => {
    const [path, anchor] = target.split("#")
    const file = path === "" ? page : relative(ROOT, join(ROOT, dirname(page), path))
    return { page, target, file: file.replaceAll("\\", "/"), anchor }
  }),
)
const exec = promisify(execFile)

function blocks(markdown: string, lang: string): string[] {
  return [...markdown.matchAll(new RegExp(`^\`\`\`${lang}\\n([\\s\\S]*?)^\`\`\`$`, "gm"))].map(
    (m) => m[1],
  )
}

const snippets = Object.values(TEXT).flatMap((markdown) => blocks(markdown, "ts"))

const API = [
  'import { createClient } from "openapi-shape/client"',
  'import { contract } from "./api"',
  'const api = createClient(contract, { baseURL: "https://api.example.com/v1" })',
  "",
].join("\n")

async function generated(): Promise<string> {
  const { code, diagnostics } = await generate(join(ROOT, "docs/examples/petstore.yaml"))
  expect(diagnostics).toStrictEqual([])
  return code
}

/** GitHub's anchor for a heading. */
function slug(heading: string): string {
  return heading
    .toLowerCase()
    .replaceAll(/[^\p{L}\p{N} _-]/gu, "")
    .replaceAll(" ", "-")
}

describe("documentation", () => {
  it("shows real generator output", async () => {
    const code = await generated()
    const example = snippets.find((b) => b.includes("Generated by openapi-shape"))
    expect(example).toBeDefined()
    // `// …` marks an elision; every other run of lines is verbatim.
    for (const chunk of example?.split(/^ *\/\/ …\n/m) ?? []) {
      expect(code).toContain(chunk.trimEnd())
    }
  })

  it("type-checks its examples against the generated file and the real library", async () => {
    const examples = snippets.filter((b) => !b.includes("Generated by openapi-shape"))
    expect(examples.length).toBeGreaterThan(0)
    const files: Record<string, string> = {
      "api.ts": await generated(),
      // Values the examples assume exist.
      "globals.d.ts": [
        "declare const token: string",
        "declare const file: Blob",
        "declare function getToken(): Promise<string>",
      ].join("\n"),
      "tsconfig.json": JSON.stringify({
        compilerOptions: {
          strict: true,
          noEmit: true,
          target: "esnext",
          module: "esnext",
          moduleResolution: "bundler",
          lib: ["esnext", "dom"],
          types: ["node"],
          typeRoots: [join(ROOT, "node_modules/@types")],
          skipLibCheck: true,
          allowImportingTsExtensions: true,
          paths: {
            "openapi-shape": [join(ROOT, "src/core/index.ts")],
            "openapi-shape/client": [join(ROOT, "src/client/index.ts")],
          },
        },
      }),
    }
    examples.forEach((example, i) => {
      // An example that imports nothing continues one that created `api`.
      const prelude = /^import /m.test(example) ? "" : API
      files[`example${i}.ts`] = `${prelude}${example}\nexport {}\n`
    })
    expect(await typecheck(files)).toBe("")
  })

  it("links to files and headings that exist", () => {
    const broken: string[] = []
    for (const { page, target, file, anchor } of LINKS) {
      const headings = (TEXT[file] ?? "").matchAll(/^#+ (.*)$/gm)
      const found = existsSync(join(ROOT, file))
      if (!found || (anchor !== undefined && ![...headings].some((h) => slug(h[1]) === anchor))) {
        broken.push(`${page}: ${target}`)
      }
    }
    expect(broken).toStrictEqual([])
  })

  it("includes documentation and linked resources in the npm package", async () => {
    await withFiles({}, async (cache) => {
      const { stdout } = await exec(
        "npm",
        ["pack", "--dry-run", "--ignore-scripts", "--json", "--cache", cache],
        { cwd: ROOT },
      )
      const [{ files }] = JSON.parse(stdout) as [{ files: Array<{ path: string }> }]
      const packed = new Set(files.map(({ path }) => path))
      const resources = new Set([...PAGES, ...LINKS.map(({ file }) => file)])
      expect([...resources].filter((file) => !packed.has(file))).toStrictEqual([])
    })
  })
})
