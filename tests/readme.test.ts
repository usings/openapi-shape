import { readFileSync } from "node:fs"
import { join } from "node:path"
import { describe, expect, it } from "vitest"
import { generate } from "../src/index"
import { typecheck } from "./helpers/tsc"

// The examples in README.md describe tests/fixtures/readme.yaml.
const ROOT = join(import.meta.dirname, "..")
const README = readFileSync(join(ROOT, "README.md"), "utf8")

function blocks(markdown: string, lang: string): string[] {
  return [...markdown.matchAll(new RegExp(`^\`\`\`${lang}\\n([\\s\\S]*?)^\`\`\`$`, "gm"))].map(
    (m) => m[1],
  )
}

async function generated(): Promise<string> {
  const { code, diagnostics } = await generate(join(ROOT, "tests/fixtures/readme.yaml"))
  expect(diagnostics).toStrictEqual([])
  return code
}

describe("documentation examples", () => {
  it("shows real generator output", async () => {
    const code = await generated()
    const example = blocks(README, "ts").find((b) => b.includes("Generated by openapi-shape"))
    expect(example).toBeDefined()
    // `// …` marks an elision; every other run of lines is verbatim.
    for (const chunk of example?.split(/^ *\/\/ …\n/m) ?? []) {
      expect(code).toContain(chunk.trimEnd())
    }
  })

  it("type-check against the generated file and the real library", async () => {
    const snippets = blocks(README, "ts").filter(
      (b) => b.includes("import") && !b.includes("Generated by openapi-shape"),
    )
    expect(snippets.length).toBeGreaterThan(4)
    const files: Record<string, string> = {
      "api.ts": await generated(),
      // Values the snippets assume exist.
      "globals.d.ts": "declare const token: string\ndeclare const file: Blob\n",
      "tsconfig.json": JSON.stringify({
        compilerOptions: {
          strict: true,
          noEmit: true,
          target: "esnext",
          module: "esnext",
          moduleResolution: "bundler",
          lib: ["esnext", "dom"],
          types: ["node"],
          typeRoots: [join(ROOT, "node_modules/@types")],
          skipLibCheck: true,
          allowImportingTsExtensions: true,
          paths: {
            "openapi-shape": [join(ROOT, "src/index.ts")],
            "openapi-shape/client": [join(ROOT, "src/client.ts")],
          },
        },
      }),
    }
    snippets.forEach((snippet, i) => {
      files[`snippet${i}.ts`] = `${snippet}\nexport {}\n`
    })
    expect(await typecheck(files)).toBe("")
  })
})
